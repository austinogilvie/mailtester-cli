#!/bin/bash
# build-denylist.sh: derive .claude/local/denylist.txt from the raw, unredacted discovery output under data/.
#
# Every email address, every domain or hostname, and every `company` value that appears anywhere in
# data/discovery_all_*.json, lowercased and deduped, minus what the public allowlist already permits
# (.claude/hooks/lib/public-content.sh), minus .invalid/.test names, minus the big public mail providers
# (gmail.com and friends are not identifying; a full address at one of them is caught by the email rule anyway).
# The output is machine-local: .claude/local/ is gitignored, and so is data/. Re-run after every discovery run.

set -euo pipefail

root=${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/../.." && pwd)}
# shellcheck source=../hooks/lib/public-content.sh
. "$root/.claude/hooks/lib/public-content.sh"
out=$PUBLIC_DENYLIST

shopt -s nullglob
files=("$root"/data/discovery_all_*.json)
shopt -u nullglob
[ ${#files[@]} -gt 0 ] || { echo "build-denylist: no data/discovery_all_*.json found; nothing to build" >&2; exit 1; }

public_provider() { # consumer mail providers and their infrastructure: common words, not identifiers
    case $1 in
        gmail.com|googlemail.com|*.google.com|google.com|outlook.com|*.outlook.com|hotmail.com|live.com \
        |yahoo.com|*.yahoo.com|*.yahoodns.net|icloud.com|me.com|*.icloud.com|protonmail.com|proton.me|*.protonmail.ch \
        |mailinator.com|*.mailinator.com|guerrillamail.com|yopmail.com|10minutemail.com|temp-mail.org|maildrop.cc \
        |dispostable.com|trashmail.com|getnada.com) return 0 ;; # disposable providers: the specs name them as a category
        *) return 1 ;;
    esac
}

keep() { # candidate -> 0 when it belongs on the denylist (a `case` inside $( ) trips bash 3.2, hence a function)
    case $1 in *.invalid|*.test) return 1 ;; esac
    case $1 in
        *@*) public_allowed_email "$1" && return 1 ;;                                 # a provider address is still identifying
        *) public_allowed_domain "$1" && return 1; public_provider "$1" && return 1 ;;
    esac
    return 0
}

candidates() {
    local strings companies
    strings=$(jq -r '.. | strings' "${files[@]}")
    companies=$(jq -r '.. | objects | (.company? // empty) | strings' "${files[@]}")
    grep -oE "$PUBLIC_EMAIL_RE" <<<"$strings" || true
    grep -oE "$PUBLIC_EMAIL_RE" <<<"$strings" | sed 's/^.*@//' || true
    grep -oE '^[A-Za-z0-9][A-Za-z0-9.-]*\.[A-Za-z]{2,}\.?$' <<<"$strings" | sed 's/\.$//' || true # whole-string domains and MX hosts
    printf '%s\n' "$companies"
}

entries=$(candidates | tr '[:upper:]' '[:lower:]' | sed -E 's/^[[:space:]]+//; s/[[:space:]]+$//' | grep -v '^$' | sort -u \
    | while IFS= read -r v; do keep "$v" && echo "$v"; done)

mkdir -p "$(dirname "$out")"
{
    echo "# Generated by .claude/scripts/build-denylist.sh on $(date -u +%Y-%m-%dT%H:%MZ) from ${#files[@]} file(s) under data/."
    echo "# One literal per line, matched case-insensitively as a substring by the public-content guard. Never commit."
    printf '%s\n' "$entries"
} >"$out"
count=$(grep -vc '^#' "$out" || true)
echo "build-denylist: $count entries written to ${out#"$root"/}"
